func TestTemplatesList(t *testing.T) {
	if len(Templates) == 0 {
		t.Fatalf("Templates slice is empty")
	}

	expectedCount := 8
	if len(Templates) != expectedCount {
		t.Errorf("Expected %d templates, got %d", expectedCount, len(Templates))
	}

	for _, tmpl := range Templates {
		if tmpl.Name == "" {
			t.Errorf("Template with empty Name found")
		}
		if tmpl.Generator == nil {
			t.Errorf("Template %s has nil Generator", tmpl.Name)
		} else {
			output := tmpl.Generator(map[string]string{"language": "Go", "app_name": "test_app"})
			if output == "" {
				t.Errorf("Template %s Generator returned empty string", tmpl.Name)
			}
		}
	}
}
