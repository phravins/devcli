func TestGenerateEditorConfig(t *testing.T) {
	tests := []struct {
		name    string
		options map[string]string
	}{
		{
			name:    "Nil options",
			options: nil,
		},
		{
			name:    "Empty options",
			options: map[string]string{},
		},
		{
			name:    "With arbitrary options",
			options: map[string]string{"language": "Go", "app_name": "test"},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := GenerateEditorConfig(tt.options)

			// Verify header
			if !strings.HasPrefix(result, "# Generated by DevCLI\n") {
				t.Errorf("GenerateEditorConfig() output missing header prefix")
			}

			// Verify required EditorConfig directives and sections
			expectedKeywords := []string{
				"root = true",
				"charset = utf-8",
				"end_of_line = lf",
				"insert_final_newline = true",
				"trim_trailing_whitespace = true",
				"indent_style = space",
				"indent_size = 2",
				"[*.{js,jsx,ts,tsx,json}]",
				"[*.{py,rb}]",
				"[*.go]",
				"indent_style = tab",
				"[Makefile]",
			}

			for _, kw := range expectedKeywords {
				if !strings.Contains(result, kw) {
					t.Errorf("GenerateEditorConfig() output missing expected directive/section: %q", kw)
				}
			}
		})
	}
}

func TestGenerateEnvFile(t *testing.T) {
	tests := []struct {
		name            string
		options         map[string]string
		expectedAppName string
	}{
		{
			name:            "Nil options defaults to my_app",
			options:         nil,
			expectedAppName: "APP_NAME=my_app",
		},
		{
			name:            "Empty options defaults to my_app",
			options:         map[string]string{},
			expectedAppName: "APP_NAME=my_app",
		},
		{
			name:            "Custom app_name option",
			options:         map[string]string{"app_name": "awesome_service"},
			expectedAppName: "APP_NAME=awesome_service",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := GenerateEnvFile(tt.options)

			if !strings.HasPrefix(result, "# Environment Configuration\n# Generated by DevCLI\n") {
				t.Errorf("GenerateEnvFile() output missing expected header")
			}

			if !strings.Contains(result, tt.expectedAppName) {
				t.Errorf("GenerateEnvFile() output expected %q, got output:\n%s", tt.expectedAppName, result)
			}
		})
	}
}

